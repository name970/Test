#!/usr/bin/env bash
# Regenerates Plauthium_Testnet.sh, the self-extracting copy of this workspace.
#
#   scripts/make_bundle.sh [OUT]     # default OUT: Plauthium_Testnet.sh
#
# Embeds every file git tracks or would track (untracked files that are not ignored),
# except PDFs and the generated script itself, as a quoted heredoc with its SHA-256,
# then appends the toolchain check, the build and the launcher. Run it on a clean tree:
# the header records the branch and commit it was built from (+dirty otherwise).
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=${1:-Plauthium_Testnet.sh}

mapfile -t FILES < <(git ls-files --cached --others --exclude-standard |
  grep -v -e '\.pdf$' -e '^Plauthium_Testnet\.sh$' | LC_ALL=C sort -u)
for f in "${FILES[@]}"; do
  [ -f "$f" ] || { echo "error: $f is tracked but missing" >&2; exit 1; }
  if [ -s "$f" ] && [ "$(tail -c 1 "$f" | od -An -c | tr -d ' ')" != '\n' ]; then
    echo "error: $f does not end with a newline (a heredoc would add one)" >&2; exit 1
  fi
  if grep -qx 'EOF' "$f"; then
    echo "error: $f contains a line 'EOF', which would end its heredoc early" >&2; exit 1
  fi
  if LC_ALL=C grep -qP '\x00' "$f"; then
    echo "error: $f is binary" >&2; exit 1
  fi
done
COUNT=${#FILES[@]}
BYTES=$(cat "${FILES[@]}" | wc -c | tr -d ' ')
BRANCH=$(git rev-parse --abbrev-ref HEAD)
COMMIT=$(git rev-parse --short=7 HEAD)
if [ -n "$(git status --porcelain --untracked-files=all -- "${FILES[@]}")" ]; then
  COMMIT="$COMMIT+dirty"
fi

sha256_of() {
  if command -v sha256sum >/dev/null 2>&1; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1
}

{
cat << '__PLAU_STATIC__'
#!/usr/bin/env bash
SEED_NODE_IP=""
if grep -q "$(printf '\r')" "$0" 2>/dev/null; then printf '%s\n' "note: converting Windows (CRLF) line endings into $0.lf" >&2; tr -d '\r' < "$0" > "$0.lf" && exec bash "$0.lf" "$@"; exit 1; fi #
if [ -z "${BASH_VERSION:-}" ]; then exec bash "$0" "$@"; fi #
#
# Plauthium_Testnet.sh: the Plauthium Public Testnet.
__PLAU_STATIC__
echo "# Source: branch $BRANCH, commit $COMMIT ($COUNT files, $BYTES bytes)."
cat << '__PLAU_STATIC__'
#
# SEED_NODE_IP (line 2) is the IP address of a public seed node, dialed on port 30333.
# Leave it empty to start a new network as its first seed node.
#
#   bash Plauthium_Testnet.sh                        write ./plauthium-workspace, then choose
#   bash Plauthium_Testnet.sh --miner|--verifier|--local [DIR]   choose without the menu
#   bash Plauthium_Testnet.sh --extract-only [DIR]   only write and check the files
#
# Requires Rust 1.89 or newer and cargo (https://rustup.rs). The first build takes a few
# minutes; later runs keep target/ and rebuild quickly. Every node creates its ML-DSA-87
# miner key (miner_key.bin) on its first run and loads it afterwards: the public node in
# ${PLAUTHIUM_HOME:-${XDG_DATA_HOME:-~/.local/share}/plauthium}, the local dev nodes in
# DIR/target/testnet/n1..n3. Ports: P2P 30333, explorer http://127.0.0.1:8080/.
#
# Generated by scripts/make_bundle.sh.
set -euo pipefail

main() {
unset CDPATH
EXTRACT_ONLY=0
MODE=
ROOT=
while [ $# -gt 0 ]; do
  case $1 in
    --extract-only) EXTRACT_ONLY=1 ;;
    --miner) MODE=miner ;;
    --verifier) MODE=verifier ;;
    --local) MODE=local ;;
    -h|--help)
      echo "Usage: bash Plauthium_Testnet.sh [--miner|--verifier|--local|--extract-only] [DIR]"
      echo "Writes the Plauthium workspace into DIR (default: ./plauthium-workspace), builds"
      echo "plauthium-node and starts a public testnet miner or verifier, or a local dev net."
      exit 0 ;;
    -*) echo "error: unknown option: $1 (try --help)" >&2; exit 2 ;;
    *)
      [ -z "$ROOT" ] || { echo "error: only one DIR may be given" >&2; exit 2; }
      ROOT=$1 ;;
  esac
  shift
done
ROOT=${ROOT:-plauthium-workspace}
case $ROOT in /*) ;; *) ROOT=./$ROOT ;; esac

if [ "$EXTRACT_ONLY" = 0 ]; then
  on=
  off=
  if [ -t 1 ]; then
    on=$'\033[1;31m'
    off=$'\033[0m'
  fi
  printf '%s' "$on"
  printf '%s\n' \
    "==============================================================================" \
    " WARNING: This is an experimental Testnet. Plauthium (PLAU) tokens have NO" \
    " real-world value. The creator makes no promises, guarantees, or financial" \
    " offerings. Do NOT share your private keys (\`miner_key.bin\`) or passwords" \
    " with anyone. Use at your own risk." \
    "=============================================================================="
  printf '%s' "$off"
fi

if [ "$EXTRACT_ONLY" = 0 ] && [ -z "$MODE" ]; then
  if [ -t 0 ]; then
    exec 3<&0
  elif { exec 3</dev/tty; } 2>/dev/null; then
    :
  else
    echo "error: no terminal to ask on; pass --miner, --verifier, --local or --extract-only" >&2
    exit 2
  fi
  echo
  echo "Plauthium Public Testnet v1"
  echo "  1) Join Public Testnet as Miner"
  echo "  2) Join Public Testnet as Verifier Only (--no-mine)"
  echo "  3) Run Local Dev Net (Spawns 3 local nodes)"
  while :; do
    printf 'Choose 1, 2 or 3: '
    if ! IFS= read -r answer <&3; then
      echo
      echo "error: no choice made" >&2
      exit 2
    fi
    case $answer in
      1) MODE=miner ;;
      2) MODE=verifier ;;
      3) MODE=local ;;
      *) echo "Please answer 1, 2 or 3."; continue ;;
    esac
    break
  done
  exec 3<&-
fi

mkdir -p "$ROOT"
cd "$ROOT"
__PLAU_STATIC__
echo "echo \"Writing $COUNT files to \$(pwd)\""
echo
for f in "${FILES[@]}"; do
  d=$(dirname "$f")
  while [ "$d" != . ]; do echo "$d"; d=$(dirname "$d"); done
done | LC_ALL=C sort -u | sed 's/^/mkdir -p /'
echo
for f in "${FILES[@]}"; do
  echo "cat << 'EOF' > $f"
  cat "$f"
  echo "EOF"
  echo
done
for f in "${FILES[@]}"; do
  if [ -x "$f" ]; then echo "chmod +x $f"; fi
done
cat << '__PLAU_STATIC__'

sha256_stdin() {
  case $1 in
    sha256sum) sha256sum ;;
    shasum) shasum -a 256 ;;
    openssl) openssl dgst -sha256 -r ;;
  esac | cut -d' ' -f1
}
hash_tool=
for tool in sha256sum shasum openssl; do
  if command -v "$tool" >/dev/null 2>&1 &&
    [ "$(printf abc | sha256_stdin "$tool" 2>/dev/null)" = ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad ]; then
    hash_tool=$tool
    break
  fi
done
if [ -z "$hash_tool" ]; then
  echo "note: no working SHA-256 tool (sha256sum, shasum or openssl) found; files written but not checked"
else
  bad=0
  while read -r sum f; do
    if [ "$(sha256_stdin "$hash_tool" < "$f")" != "$sum" ]; then
      echo "error: $f does not match its checksum" >&2
      bad=1
    fi
  done << 'EOF'
__PLAU_STATIC__
for f in "${FILES[@]}"; do
  echo "$(sha256_of "$f")  $f"
done
echo "EOF"
cat << '__PLAU_STATIC__'
  if [ "$bad" = 1 ]; then
    echo "error: this copy of Plauthium_Testnet.sh is incomplete or altered; download it again" >&2
    exit 1
  fi
__PLAU_STATIC__
echo "  echo \"All $COUNT files written and verified ($COMMIT).\""
cat << '__PLAU_STATIC__'
fi

if [ "$EXTRACT_ONLY" = 1 ]; then
  printf 'Done (--extract-only). To build and start a node: cd %q && scripts/testnet.sh\n' "$(pwd)"
  exit 0
fi

if ! command -v cargo >/dev/null 2>&1 && [ -f "$HOME/.cargo/env" ]; then
  . "$HOME/.cargo/env"
fi
command -v cargo >/dev/null 2>&1 || {
  echo "error: cargo not found. Install Rust 1.89 or newer from https://rustup.rs, then run this script again." >&2
  exit 1
}
rust_version=$(rustc --version 2>/dev/null | cut -d' ' -f2) || rust_version=
case $rust_version in
  [0-9]*.[0-9]*)
    rust_major=${rust_version%%.*}
    rust_minor=${rust_version#*.}
    rust_minor=${rust_minor%%.*}
    if [ "$rust_major" -lt 1 ] || { [ "$rust_major" -eq 1 ] && [ "$rust_minor" -lt 89 ]; }; then
      echo "error: Rust 1.89 or newer is required (found $rust_version). Run: rustup update stable" >&2
      exit 1
    fi ;;
  *) echo "note: could not read the Rust version; continuing (Rust 1.89 or newer is required)" ;;
esac

export CARGO_TARGET_DIR="$PWD/target"
echo "Building plauthium-node (release)..."
cargo build --release -p node

export SEED_NODE_IP
export PLAUTHIUM_WARNED=1
exec bash scripts/testnet.sh --no-build "--$MODE"
}

main "$@"
__PLAU_STATIC__
} > "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
chmod +x "$OUT"
echo "Wrote $OUT ($COUNT files, $BYTES bytes, $BRANCH @ $COMMIT)"
